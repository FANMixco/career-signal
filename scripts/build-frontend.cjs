const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");
const frontendRoot = path.join(repoRoot, "frontend");
const appSourceRoot = path.join(frontendRoot, "src", "app");
const contentSourceRoot = path.join(frontendRoot, "src", "content");

const appSourceFiles = [
  "00-state.js",
  "01-utils.js",
  "02-ui-rendering.js",
  "03-session-io.js",
  "04-backend-settings.js",
  "05-form-controls.js",
  "06-precheck.js",
  "07-analysis.js",
  "08-bootstrap.js"
];

function requireEsbuild() {
  const candidates = [
    "esbuild",
    path.join(repoRoot, "backend", "node_modules", "esbuild")
  ];

  for (const candidate of candidates) {
    try {
      return require(candidate);
    } catch {
      // Try the next known install location.
    }
  }

  throw new Error("Could not find esbuild. Run npm --prefix backend install before building the frontend.");
}

function readText(relativePath) {
  return fs.readFileSync(path.join(repoRoot, relativePath), "utf8");
}

function readJson(relativePath) {
  return JSON.parse(readText(relativePath));
}

function minifyJavaScript(source, sourcefile) {
  const esbuild = requireEsbuild();
  return esbuild.transformSync(source, {
    sourcefile,
    minify: true,
    format: "iife",
    target: "es2019",
    legalComments: "none"
  }).code;
}

function minifyCss(source, sourcefile) {
  const esbuild = requireEsbuild();
  return esbuild.transformSync(source, {
    sourcefile,
    loader: "css",
    minify: true,
    legalComments: "none"
  }).code;
}

function writeGeneratedFile(relativePath, code, comment = "// Generated by scripts/build-frontend.cjs. Edit frontend/src instead.") {
  const outputPath = path.join(repoRoot, relativePath);
  fs.writeFileSync(
    outputPath,
    `${comment}\n${code}\n`,
    "utf8"
  );
}

function configSource() {
  const configSource = readText("frontend/src/config.js");
  const loaderIndex = configSource.indexOf("\nfunction loadContentJson");

  if (loaderIndex < 0) {
    throw new Error("Could not find loadContentJson in frontend/src/config.js.");
  }

  const resolveApiBaseUrlSource = configSource.slice(0, loaderIndex);
  const baseContent = readJson("frontend/src/content/app.en.json");
  const translations = {};
  const contentFiles = fs
    .readdirSync(contentSourceRoot)
    .filter((fileName) => /^app\.[a-z]{2}\.json$/.test(fileName))
    .sort();

  for (const fileName of contentFiles) {
    const language = /^app\.([a-z]{2})\.json$/.exec(fileName)?.[1];
    if (!language || language === "en") continue;
    translations[language] = readJson(path.join("frontend", "src", "content", fileName));
  }

  return `
${resolveApiBaseUrlSource}
const baseContent = ${JSON.stringify(baseContent)};

window.CAREER_SIGNAL_CONFIG = {
  apiBaseUrl: resolveApiBaseUrl(window.location),
  pdfMaxBytes: 5 * 1024 * 1024,
  ...baseContent,
  translations: ${JSON.stringify(translations)}
};
`;
}

function appSource() {
  return appSourceFiles
    .map((fileName) => readText(path.join("frontend", "src", "app", fileName)))
    .join("\n");
}

function bmcWidgetSource() {
  return readText("frontend/src/bmc-widget.js");
}

function buildRuntime() {
  const source = [
    configSource(),
    appSource(),
    bmcWidgetSource()
  ].join("\n");

  writeGeneratedFile("frontend/app.min.js", minifyJavaScript(source, "frontend/app.min.js"));
}

function buildStyles() {
  const source = readText("frontend/src/styles.css");
  writeGeneratedFile(
    "frontend/styles.min.css",
    minifyCss(source, "frontend/styles.min.css"),
    "/* Generated by scripts/build-frontend.cjs. Edit frontend/src instead. */"
  );
}

function buildContentJson() {
  fs.mkdirSync(path.join(frontendRoot, "content"), { recursive: true });
  const contentFiles = fs
    .readdirSync(contentSourceRoot)
    .filter((fileName) => /^app\.[a-z]{2}\.json$/.test(fileName))
    .sort();

  for (const fileName of contentFiles) {
    const content = readJson(path.join("frontend", "src", "content", fileName));
    fs.writeFileSync(
      path.join(frontendRoot, "content", fileName),
      `${JSON.stringify(content)}\n`,
      "utf8"
    );
  }
}

buildRuntime();
buildStyles();
buildContentJson();

console.log("Built minified frontend/app.min.js, frontend/styles.min.css, and frontend/content/app.*.json.");
